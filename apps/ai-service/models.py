"""
GeoBuild AI — Building Specification Models
Core Pydantic models for the BuildingSpec and related schemas.
All units are metres unless noted otherwise.
"""

from __future__ import annotations
from typing import Literal
from pydantic import BaseModel, Field


class Facade(BaseModel):
    """Facade configuration for the building."""
    style: Literal[
        "contemporary_pakistani",
        "modern_minimal",
        "classical",
        "mughal_inspired",
        "industrial_brick",
        "spanish_villa",
        "commercial_plaza"
    ] = "contemporary_pakistani"
    primaryMaterial: Literal[
        "plaster_white",
        "plaster_beige",
        "brick_red",
        "stone_grey",
        "glass_panel"
    ] = "plaster_beige"
    accentMaterial: Literal[
        "plaster_white",
        "plaster_beige",
        "brick_red",
        "stone_grey",
        "glass_panel",
        "marble_white",
        "wood_dark"
    ] = "brick_red"
    hasJali: bool = False
    hasBalcony: bool = True
    hasVeranda: bool = False


class ParkingConfig(BaseModel):
    """Parking configuration."""
    cars: int = Field(1, ge=0, le=8, description="Number of car parking spots")
    type: Literal["covered", "open", "basement"] = "covered"


class RoomConfig(BaseModel):
    """Room configuration per floor or total."""
    bedrooms: int = Field(3, ge=0, le=12)
    bathrooms: int = Field(3, ge=0, le=12)
    kitchens: int = Field(1, ge=1, le=3)
    livingRooms: int = Field(1, ge=0, le=4)
    drawingRoom: bool = True
    diningRoom: bool = True
    storeRoom: bool = False
    servantQuarter: bool = False


class BuildingSpec(BaseModel):
    """
    The core building specification.
    Generated by the LLM from natural-language input, validated by Pydantic.
    The LLM only produces this JSON — never geometry.
    """
    # Structure
    floors: int = Field(2, ge=1, le=6, description="Number of above-ground floors")
    basement: bool = Field(False, description="Whether the building has a basement")
    floorHeightM: float = Field(3.05, ge=2.7, le=4.5, description="Floor-to-floor height in metres")

    # Rooms
    rooms: RoomConfig = Field(default_factory=RoomConfig)

    # Parking
    parking: ParkingConfig = Field(default_factory=ParkingConfig)

    # Roof
    rooftopTerrace: bool = Field(False, description="Accessible rooftop terrace")
    rooftopPergola: bool = Field(False, description="Pergola on the rooftop")
    waterTank: bool = Field(True, description="Overhead water tank")

    # Facade
    facade: Facade = Field(default_factory=Facade)

    # Boundary
    boundaryWall: bool = Field(True, description="Boundary wall around the plot")
    mainGateStyle: Literal["modern", "classical", "ornate", "minimal"] = "modern"


class InterpretRequest(BaseModel):
    """Request to interpret a natural-language building description."""
    prompt: str = Field(..., min_length=5, max_length=2000)
    city: str = Field("lahore", pattern=r"^(lahore|islamabad|karachi)$")
    plot_area_sqm: float | None = Field(None, ge=50, le=10000)


class InterpretResponse(BaseModel):
    """Response from the interpret endpoint."""
    spec: BuildingSpec
    assumptions: list[str] = Field(
        default_factory=list,
        description="Assumptions made by the AI when fields were not specified"
    )
    confidence: float = Field(0.9, ge=0.0, le=1.0)


class PatchOperation(BaseModel):
    """A single patch operation on the BuildingSpec."""
    op: Literal["replace", "increment", "toggle"] = "replace"
    path: str = Field(..., description="Dot-notation path, e.g. 'rooms.bedrooms' or 'facade.style'")
    value: int | float | bool | str | None = None


class PatchRequest(BaseModel):
    """Request to patch an existing BuildingSpec via natural language."""
    command: str = Field(..., min_length=2, max_length=500)
    current_spec: BuildingSpec


class PatchResponse(BaseModel):
    """Response from the patch endpoint."""
    operations: list[PatchOperation]
    updated_spec: BuildingSpec
    explanation: str = ""
    assumptions: list[str] = Field(default_factory=list)


class AnalysisResult(BaseModel):
    """Development feasibility analysis."""
    plot_area_sqm: float
    plot_area_marla: float
    building_footprint_sqm: float
    coverage_pct: float
    far_ratio: float
    total_covered_area_sqm: float
    total_height_m: float
    parking_spaces: int
    estimated_cost_pkr: CostEstimate | None = None
    compliance_issues: list[ComplianceIssue] = Field(default_factory=list)
    disclaimer: str = "Preliminary check — not legal or regulatory approval."


class CostEstimate(BaseModel):
    """Construction cost estimate in PKR."""
    grey_structure: int
    finishing: int
    total: int
    tier: Literal["economy", "standard", "premium"] = "standard"
    rate_per_sqft: int
    total_sqft: float


class ComplianceIssue(BaseModel):
    """A single compliance issue found during analysis."""
    rule: str
    expected: str
    actual: str
    severity: Literal["error", "warning", "info"] = "warning"
